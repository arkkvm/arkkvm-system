# shellcheck shell=sh
# dhcpcd backend — all dhcpcd operations live only in this file

# Parse yiaddr (client IP) from a dhcpcd binary lease file (RFC2131 message @ offset 16).
nwu_dhcpcd_lease_yiaddr() {
	lease="$1"
	[ -f "$lease" ] || return 1
	# shellcheck disable=SC2046
	set -- $(od -An -t u1 -N 4 -j 16 "$lease" 2>/dev/null)
	[ "$#" -eq 4 ] || return 1
	case "$1$2$3$4" in
	*[!0-9]*) return 1 ;;
	esac
	[ "$1" -le 255 ] && [ "$2" -le 255 ] && [ "$3" -le 255 ] && [ "$4" -le 255 ] || return 1
	# Reject 0.0.0.0
	if [ "$1" -eq 0 ] && [ "$2" -eq 0 ] && [ "$3" -eq 0 ] && [ "$4" -eq 0 ]; then
		return 1
	fi
	echo "$1.$2.$3.$4"
}

# Reconstruct dhcpcd's DHCPv4 ClientID (RFC4361): 0xff + IAID(4) + DUID.
# dhcpcd-9 default IAID = last 4 bytes of hardware address (else iface name);
# DUID from $DHCPCD_DB/duid.
nwu_dhcpcd_rfc4361_clientid_hex() {
	iface="${1:-$NET_IF}"
	db="${DHCPCD_DB:-/userdata/arkkvm/dhcpcd}"
	duid_file="$db/duid"
	[ -n "$iface" ] || return 1
	[ -f "$duid_file" ] || return 1
	duid=$(tr -d ':
	 ' <"$duid_file" | tr 'A-F' 'a-f')
	echo "$duid" | grep -Eq '^[0-9a-f]+$' || return 1
	[ "${#duid}" -ge 8 ] || return 1

	iaid=""
	mac=$(cat "/sys/class/net/$iface/address" 2>/dev/null | tr -d ':' | tr 'A-F' 'a-f')
	if echo "$mac" | grep -Eq '^[0-9a-f]{8,}$'; then
		iaid=$(printf '%s' "$mac" | awk '{print substr($0, length($0)-7)}')
	else
		_hex=$(printf '%s' "$iface" | od -An -tx1 | tr -d ' 
' | tr 'A-F' 'a-f')
		while [ "${#_hex}" -lt 8 ]; do
			_hex="00${_hex}"
		done
		iaid=$(printf '%s' "$_hex" | awk '{print substr($0, length($0)-7)}')
	fi
	echo "$iaid" | grep -Eq '^[0-9a-f]{8}$' || return 1
	echo "ff${iaid}${duid}"
}

# After OTA migrate has read yiaddr for udhcpc -r, delete the legacy lease (one-shot).
nwu_dhcpcd_consume_legacy_lease() {
	iface="${1:-$NET_IF}"
	db="${DHCPCD_DB:-/userdata/arkkvm/dhcpcd}"
	dlease="$db/${iface}.lease"
	[ -f "$dlease" ] || return 0
	rm -f "$dlease" 2>/dev/null || true
	msg_info "removed legacy dhcpcd lease $dlease"
	nwu_log "removed legacy dhcpcd lease $dlease"
}

nwu_dhcpcd_running() {
	[ -f "$DHCPCD_PIDFILE" ] && kill -0 "$(cat "$DHCPCD_PIDFILE" 2>/dev/null)" 2>/dev/null
}

nwu_dhcpcd_stop() {
	msg_step "Stop dhcpcd"
	if nwu_skip_netlink; then
		msg_info "[dry-run] dhcpcd stop"
		rm -f "$DHCPCD_PIDFILE" 2>/dev/null || true
		return 0
	fi
	if [ -x /etc/init.d/S15dhcpcd ]; then
		/etc/init.d/S15dhcpcd stop 2>/dev/null || true
	fi
	killall dhcpcd 2>/dev/null || true
	nwu_log "dhcpcd stopped"
}

nwu_dhcpcd_start() {
	msg_step "Start dhcpcd"
	if nwu_skip_netlink; then
		msg_info "[dry-run] dhcpcd start"
		mkdir -p "$(dirname "$DHCPCD_PIDFILE")"
		echo "99999" >"$DHCPCD_PIDFILE" 2>/dev/null || true
		return 0
	fi

	if [ ! -f "$DHCPCD_CONF" ]; then
		die "Missing $DHCPCD_CONF, cannot start dhcpcd"
	fi

	if nwu_dhcpcd_running; then
		nwu_dhcpcd_rebind
		return 0
	fi

	if [ -x /etc/init.d/S15dhcpcd ]; then
		/etc/init.d/S15dhcpcd start 2>/dev/null || dhcpcd -f "$DHCPCD_CONF" -b
	else
		dhcpcd -f "$DHCPCD_CONF" -b
	fi
	nwu_dhcpcd_rebind
	nwu_log "dhcpcd started"
}

nwu_dhcpcd_rebind() {
	msg_step "dhcpcd rebind $NET_IF"
	if nwu_skip_netlink; then
		msg_info "[dry-run] dhcpcd -n $NET_IF"
		return 0
	fi
	dhcpcd -n "$NET_IF" >/dev/null 2>&1 || true
	nwu_log "dhcpcd rebind $NET_IF"
}

nwu_dhcpcd_renew() {
	nwu_dhcpcd_rebind
}

nwu_dhcpcd_release() {
	msg_step "dhcpcd release $NET_IF"
	if nwu_skip_netlink; then
		msg_info "[dry-run] dhcpcd -k $NET_IF"
		return 0
	fi
	dhcpcd -k "$NET_IF" 2>/dev/null || true
	nwu_log "dhcpcd release $NET_IF"
}

nwu_dhcpcd_restart() {
	nwu_dhcpcd_stop
	sleep 1
	nwu_dhcpcd_start
}

nwu_dhcpcd_write_lease_from_system() {
	# When dhcpcd has no udhcpc-style hook, synthesize lease file from system state (like gen_info)
	lease=$(nwu_lease_path)
	if nwu_skip_netlink; then
		mkdir -p "$(dirname "$lease")"
		cat >"$lease" <<EOF
# generated by network-config-unified (dhcpcd backend)
ip=192.168.5.118
router=192.168.5.1
dns=192.168.5.1
domain=local
backend=dhcpcd
EOF
		return 0
	fi

	ip=$(ip -4 -o addr show dev "$NET_IF" 2>/dev/null | awk '{print $4}' | head -1 | cut -d/ -f1)
	ip_cidr=$(ip -4 -o addr show dev "$NET_IF" 2>/dev/null | awk '{print $4}' | head -1)
	subnet="${ip_cidr#*/}"
	router=$(nwu_ipv4_default_gateway "$NET_IF")
	dns=$(grep '^nameserver' "$RESOLV_CONF" 2>/dev/null | awk '{print $2}' | tr '\n' ' ')
	domain=$(grep '^search' "$RESOLV_CONF" 2>/dev/null | awk '{print $2; exit}')
	[ -z "$domain" ] && domain="${CONF_DOMAIN:-local}"
	hostname=$(cat /etc/hostname 2>/dev/null | tr -d '\n')
	router=$(nwu_ipv4_sanitize "$router")
	serverid="${router:-}"
	siaddr="${router:-}"
	mkdir -p "$(dirname "$lease")"
	{
		echo "# generated by network-config-unified (dhcpcd backend)"
		echo "ip=${ip:-}"
		echo "subnet=${subnet:-}"
		echo "router=${router:-}"
		echo "dns=${dns:-}"
		echo "domain=${domain:-}"
		echo "hostname=${hostname:-}"
		echo "serverid=${serverid:-}"
		echo "siaddr=${siaddr:-}"
		echo "backend=dhcpcd"
	} >"$lease"
}

nwu_dhcpcd_show_lease() {
	nwu_dhcpcd_write_lease_from_system
	lease=$(nwu_lease_path)
	if [ -f "$lease" ]; then
		cat "$lease"
	else
		msg_warn "Lease file not found: $lease"
		return 1
	fi
}
