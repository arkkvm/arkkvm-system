#!/bin/sh
# udhcpc hook — udhcpc backend only; writes unified lease file format
[ -z "$1" ] && exit 1

if [ -n "${NWU_ROOT:-}" ] && [ -f "$NWU_ROOT/lib/common.sh" ]; then
	# shellcheck source=/dev/null
	. "$NWU_ROOT/lib/common.sh"
fi

RESOLV_CONF="${RESOLV_CONF:-/etc/resolv.conf}"
interface="${interface:-eth0}"
# Save concrete lease path before any nwu_load_paths (which resets LEASE_FILE to a %s format).
_HOOK_LEASE="${LEASE_FILE:-}"
case "$_HOOK_LEASE" in
''|*%*)
	_HOOK_LEASE="/run/udhcpc.${interface}.info"
	;;
esac
LEASE_FILE="$_HOOK_LEASE"

msg_info() { echo "[udhcpc-hook] $*" >&2; }

nwu_hook_skip_net() {
	[ "${NWU_DRY_RUN:-0}" = "1" ] && return 0
	return 1
}

HOOK_APPLY_ROUTE_DNS=1
HOOK_ENFORCE_PRIMARY_DEFAULT=0

nwu_hook_route_dns_policy() {
	HOOK_APPLY_ROUTE_DNS=1
	HOOK_ENFORCE_PRIMARY_DEFAULT=0

	[ -n "${NWU_ROOT:-}" ] || return 0
	[ -f "$NWU_ROOT/lib/config.sh" ] || return 0
	[ -f "$NWU_ROOT/lib/parse.sh" ] || return 0

	# shellcheck source=/dev/null
	. "$NWU_ROOT/lib/config.sh"
	# shellcheck source=/dev/null
	. "$NWU_ROOT/lib/parse.sh"
	nwu_load_paths
	# nwu_load_paths resets LEASE_FILE to the printf format — restore concrete path.
	LEASE_FILE="$_HOOK_LEASE"

	conf="${NETWORK_CONF:-/userdata/arkkvm/network.conf}"
	[ -f "$conf" ] || return 0
	nwu_conf_parse "$conf" >/dev/null 2>&1 || return 0

	if [ "${CONF_VLAN_ENABLED:-false}" != "true" ] || [ "${CONF_VLAN_APPLY_MODE:-committed}" != "committed" ]; then
		return 0
	fi

	primary_iface="${CONF_VLAN_PARENT}.${CONF_VLAN_PRIMARY_ID}"
	if [ "$interface" = "$primary_iface" ]; then
		HOOK_ENFORCE_PRIMARY_DEFAULT=1
	else
		HOOK_APPLY_ROUTE_DNS=0
	fi
}

[ -n "$broadcast" ] && BROADCAST="broadcast $broadcast"
[ -n "$subnet" ] && NETMASK="netmask $subnet"

case "$1" in
deconfig)
	if nwu_hook_skip_net; then rm -f "$LEASE_FILE"; exit 0; fi
	ip -4 addr flush dev "$interface" 2>/dev/null || true
	rm -f "$LEASE_FILE"
	;;
renew|bound)
	if nwu_hook_skip_net; then
		mkdir -p "$(dirname "$LEASE_FILE")"
		cat >"$LEASE_FILE" <<EOF
# generated by network-config-unified udhcpc-hook (test mode)
ip=$ip
subnet=$subnet
broadcast=$broadcast
router=$router
dns=$dns
domain=$domain
hostname=$hostname
lease=$lease
serverid=${serverid:-$siaddr}
siaddr=$siaddr
backend=udhcpc
EOF
		exit 0
	fi
	if command -v ip >/dev/null 2>&1; then
		ip -4 addr flush dev "$interface" 2>/dev/null || true
		# busybox udhcpc gives dotted netmask in $subnet; convert to prefix length.
		_prefix="$subnet"
		case "$_prefix" in
		'') _prefix=24 ;;
		*[!0-9.]*) _prefix=24 ;;
		*.*)
			case "$_prefix" in
			255.255.255.255) _prefix=32 ;;
			255.255.255.254) _prefix=31 ;;
			255.255.255.252) _prefix=30 ;;
			255.255.255.248) _prefix=29 ;;
			255.255.255.240) _prefix=28 ;;
			255.255.255.224) _prefix=27 ;;
			255.255.255.192) _prefix=26 ;;
			255.255.255.128) _prefix=25 ;;
			255.255.255.0) _prefix=24 ;;
			255.255.254.0) _prefix=23 ;;
			255.255.252.0) _prefix=22 ;;
			255.255.248.0) _prefix=21 ;;
			255.255.240.0) _prefix=20 ;;
			255.255.224.0) _prefix=19 ;;
			255.255.192.0) _prefix=18 ;;
			255.255.128.0) _prefix=17 ;;
			255.255.0.0) _prefix=16 ;;
			255.254.0.0) _prefix=15 ;;
			255.252.0.0) _prefix=14 ;;
			255.248.0.0) _prefix=13 ;;
			255.240.0.0) _prefix=12 ;;
			255.224.0.0) _prefix=11 ;;
			255.192.0.0) _prefix=10 ;;
			255.128.0.0) _prefix=9 ;;
			255.0.0.0) _prefix=8 ;;
			*)
				_prefix=$(echo "$_prefix" | awk -F. '{
					n=0
					for (i=1;i<=4;i++) {
						d=$i+0
						if (d==255) n+=8
						else if (d==254) n+=7
						else if (d==252) n+=6
						else if (d==248) n+=5
						else if (d==240) n+=4
						else if (d==224) n+=3
						else if (d==192) n+=2
						else if (d==128) n+=1
						else if (d==0) { print n; exit }
						else { print 24; exit }
					}
					print n
				}')
				;;
			esac
			;;
		# already a numeric prefix length
		esac
		ip addr add "$ip/${_prefix}" dev "$interface" 2>/dev/null || true
		ip link set dev "$interface" up
	fi
	nwu_hook_route_dns_policy
	if [ "$HOOK_APPLY_ROUTE_DNS" = "1" ] && [ -n "$router" ]; then
		while ip route del default 2>/dev/null; do :; done
		for i in $router; do
			ip route replace default via "$i" dev "$interface" 2>/dev/null || true
			break
		done
	fi
	mkdir -p "$(dirname "$RESOLV_CONF")" "$(dirname "$LEASE_FILE")"
	if [ "$HOOK_APPLY_ROUTE_DNS" = "1" ]; then
		: >"$RESOLV_CONF"
		[ -n "$domain" ] && echo "search $domain" >>"$RESOLV_CONF"
		for i in $dns; do
			echo "nameserver $i" >>"$RESOLV_CONF"
		done
	else
		msg_info "skip route/dns update on $interface (VLAN committed policy)"
	fi
	cat >"$LEASE_FILE" <<EOF
# generated by network-config-unified udhcpc-hook
ip=$ip
subnet=$subnet
broadcast=$broadcast
router=$router
dns=$dns
domain=$domain
hostname=$hostname
lease=$lease
serverid=${serverid:-$siaddr}
siaddr=$siaddr
backend=udhcpc
EOF
	# Persist successful bind for later OTA/reboot -r (survives /run wipe).
	if [ -n "$ip" ] && [ -n "${NWU_ROOT:-}" ] && [ -f "$NWU_ROOT/lib/ipv4.sh" ]; then
		# shellcheck source=/dev/null
		. "$NWU_ROOT/lib/common.sh" 2>/dev/null || true
		# shellcheck source=/dev/null
		. "$NWU_ROOT/lib/config.sh" 2>/dev/null || true
		nwu_load_paths 2>/dev/null || true
		LEASE_FILE="$_HOOK_LEASE"
		# shellcheck source=/dev/null
		. "$NWU_ROOT/lib/ipv4.sh" 2>/dev/null || true
		NET_IF="$interface"
		if [ -z "${NWU_DHCP_REQUEST_IP:-}" ] || [ "$ip" = "$NWU_DHCP_REQUEST_IP" ]; then
			_src=udhcpc
			_lp=$(nwu_dhcp_last_path "$interface" 2>/dev/null || true)
			if [ -n "$_lp" ] && grep -q '^source=dhcpcd$' "$_lp" 2>/dev/null; then
				_src=dhcpcd
			fi
			nwu_dhcp_write_last "$interface" "$ip" "$_src" 2>/dev/null || true
		fi
	fi
	if [ "$HOOK_ENFORCE_PRIMARY_DEFAULT" = "1" ] && [ -f "$NWU_ROOT/lib/vlan.sh" ]; then
		# shellcheck source=/dev/null
		. "$NWU_ROOT/lib/vlan.sh"
		nwu_vlan_enforce_primary_default_route 2>/dev/null || true
	fi
	;;
esac
exit 0
